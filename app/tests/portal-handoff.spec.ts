import { test, expect, type Page } from '@playwright/test'

if (!['localhost', '127.0.0.1'].includes(new URL(process.env.VITE_SUPABASE_URL!).hostname)) throw new Error('Local backend required')

// Agreed seam: independent real browsers → the committed local Supabase stack.
// Catalogs and low-level authorization permutations remain in their feature suites.
test('GM and two players complete one keyboard-accessible cycle, recover a failed save and transfer ownership', async ({ browser }) => {
  test.setTimeout(90000)
  const contexts = await Promise.all([browser.newContext(), browser.newContext(), browser.newContext()])
  const [gm, one, two] = await Promise.all(contexts.map(context => context.newPage()))
  const cycle = (page: Page) => page.getByRole('region', { name: 'Campaign cycle', exact: true })
  const plan = (page: Page) => page.getByRole('article', { name: 'Score plan · The relay', exact: true })
  const aftermath = (page: Page) => page.getByRole('region', { name: 'Aftermath review', exact: true })
  try {
    await gm.goto('/')
    await gm.getByLabel('Campaign name', { exact: true }).focus()
    await gm.keyboard.type('The complete frequency')
    await gm.keyboard.press('Tab')
    await expect(gm.getByRole('button', { name: 'Create campaign', exact: true })).toBeFocused()
    await gm.keyboard.press('Enter')
    const invitation = await gm.getByLabel('Player invitation').inputValue()
    for (const page of [one, two]) {
      await page.goto('/')
      await page.getByLabel('Invitation', { exact: true }).fill(invitation)
      await page.getByLabel('Invitation', { exact: true }).press('Enter')
      await expect(page.getByTestId('campaign-role')).toHaveText('Player')
    }
    expect(await one.getByLabel('Your participant ID').inputValue()).not.toBe(await two.getByLabel('Your participant ID').inputValue())
    // This long dossier needs a keyboard path that skips preceding editors.
    const sections = one.getByRole('navigation', { name: 'Campaign sections', exact: true })
    await expect(sections).toBeVisible()
    await sections.getByRole('tab', { name: 'Characters', exact: true }).focus()
    await one.keyboard.press('Enter')
    await one.keyboard.press('Tab')
    await expect(one.getByRole('tabpanel', { name: 'Characters', exact: true })).toBeFocused()
    await one.getByRole('tab', { name: 'Characters', exact: true }).click()
    await one.getByLabel('New character name', { exact: true }).fill('Moth')
    await one.getByRole('button', { name: 'Create Hound', exact: true }).click()
    await expect(one.getByRole('article', { name: 'Moth dossier', exact: true })).toContainText('Published baseline:')
    await expect(one.getByRole('region', { name: 'Condition records', exact: true }).getByLabel('Passing Harm 1', { exact: true })).toBeVisible()
    const equipment = one.getByRole('region', { name: 'Equipment and advancement records', exact: true })
    await expect(equipment.getByText('book p.25 says 0', { exact: false })).toBeHidden()
    await equipment.locator('summary').filter({ hasText: 'Load rules' }).click()
    await expect(equipment.getByText('book p.25 says 0', { exact: false })).toBeVisible()
    await expect(one.getByRole('region', { name: 'Equipment and advancement records', exact: true })).toContainText('book p.25 says 0')
    await two.getByRole('tab', { name: 'Characters', exact: true }).click()
    await two.getByLabel('New character name', { exact: true }).fill('Kite')
    await two.getByLabel('Playbook', { exact: true }).selectOption('Operative')
    await two.getByRole('button', { name: 'Create Operative', exact: true }).click()
    await gm.getByRole('tab', { name: 'Crew', exact: true }).click()
    await gm.getByLabel('Crew name', { exact: true }).fill('Station Six')
    await gm.getByLabel('Crew type', { exact: true }).selectOption('Shadows')
    await gm.getByRole('button', { name: 'Create crew', exact: true }).click()
    await expect(gm.getByRole('region', { name: 'Crew dossier', exact: true }).getByLabel('Stacks', { exact: true })).toHaveValue('2')

    for (const page of [gm, one, two]) await page.getByRole('tab', { name: 'Cycle', exact: true }).click()
    await cycle(one).getByLabel('Activity character', { exact: true }).selectOption({ label: 'Moth' })
    await cycle(one).getByLabel('Activity description', { exact: true }).fill('Visit our signal engineer; result stays manual')
    await cycle(one).getByRole('button', { name: 'Record activity', exact: true }).click()
    await expect(cycle(two).getByRole('article', { name: 'Free play · Moth', exact: true })).toBeVisible()
    await cycle(gm).getByLabel('Campaign phase', { exact: true }).selectOption('planning_meeting')
    await cycle(gm).getByRole('button', { name: 'Set phase', exact: true }).click()
    await cycle(one).getByLabel('Opportunity target', { exact: true }).fill('The relay')
    await cycle(one).getByRole('button', { name: 'Sketch opportunity', exact: true }).click()
    const opportunity = cycle(gm).getByRole('article', { name: 'Opportunity · The relay', exact: true })
    await opportunity.getByLabel('Target Tier', { exact: true }).fill('2')
    await opportunity.getByLabel('Potential payout', { exact: true }).fill('6')
    await opportunity.getByRole('button', { name: 'Save opportunity', exact: true }).click()
    await expect(opportunity.getByRole('status')).toHaveText('Saved.')
    await opportunity.getByRole('button', { name: 'Select as primary score', exact: true }).click()
    await expect(plan(one)).toBeVisible()
    await expect(plan(two)).toBeVisible()
    await plan(one).getByLabel('Opening gambit', { exact: true }).fill('Enter below the tracks')
    await plan(two).getByLabel('Score loadout', { exact: true }).selectOption('Quiet')
    await Promise.all([plan(one).getByRole('button', { name: 'Save plan', exact: true }).click(), plan(two).getByRole('button', { name: 'Save plan', exact: true }).click()])
    for (const page of [gm, one, two]) {
      await expect(plan(page).getByLabel('Opening gambit', { exact: true })).toHaveValue('Enter below the tracks')
      await expect(plan(page).getByLabel('Score loadout', { exact: true })).toHaveValue('Quiet')
    }
    await plan(two).getByLabel('Shared planning notes', { exact: true }).fill('Retain this agreement after reconnect')
    await contexts[2].setOffline(true)
    await plan(two).getByRole('button', { name: 'Save plan', exact: true }).click()
    await expect(plan(two).getByRole('alert')).toContainText('Record was not saved')
    await expect(plan(two).getByLabel('Shared planning notes', { exact: true })).toHaveValue('Retain this agreement after reconnect')
    await contexts[2].setOffline(false)
    await plan(two).getByRole('button', { name: 'Save plan', exact: true }).click()
    await expect(plan(one).getByLabel('Shared planning notes', { exact: true })).toHaveValue('Retain this agreement after reconnect')

    const score = gm.getByRole('article', { name: 'Score · The relay', exact: true })
    await score.getByRole('button', { name: 'Start score', exact: true }).click()
    await score.getByRole('button', { name: 'Confirm start', exact: true }).click()
    await expect(score.getByText('Status: active', { exact: true })).toBeVisible()
    await score.getByRole('button', { name: 'Complete score', exact: true }).click()
    await score.getByRole('button', { name: 'Confirm complete', exact: true }).click()
    await expect(score.getByText('Status: completed', { exact: true })).toBeVisible()
    await cycle(gm).getByLabel('Campaign phase', { exact: true }).selectOption('aftermath')
    await cycle(gm).getByRole('button', { name: 'Set phase', exact: true }).click()
    await aftermath(gm).getByLabel('Effect record type', { exact: true }).selectOption('crew')
    await aftermath(gm).getByLabel('Effect field', { exact: true }).selectOption('stacks')
    await aftermath(gm).getByLabel('Proposed value', { exact: true }).fill('4')
    await aftermath(gm).getByRole('button', { name: 'Add reviewed effect', exact: true }).click()
    await aftermath(gm).getByLabel('Shared Aftermath recap', { exact: true }).fill('Signal delivered; agreed crew balance is four stacks')
    await aftermath(gm).getByRole('button', { name: 'Save proposal for review', exact: true }).click()
    await expect(aftermath(one).getByRole('article', { name: 'Pending Aftermath proposal', exact: true })).toHaveCount(0)
    await aftermath(gm).getByRole('button', { name: 'Confirm all reviewed changes', exact: true }).click()
    for (const page of [gm, one, two]) {
      await expect(aftermath(page).getByRole('article', { name: 'Aftermath receipt', exact: true })).toHaveCount(1)
      await page.getByRole('tab', { name: 'Crew', exact: true }).click()
      await expect(page.getByRole('region', { name: 'Crew dossier', exact: true }).getByLabel('Stacks', { exact: true })).toHaveValue('4')
      await page.getByRole('tab', { name: 'Cycle', exact: true }).click()
    }
    await aftermath(gm).getByLabel('Manual record title', { exact: true }).fill('PRIVATE_HANDOFF_MANDATE')
    await aftermath(gm).getByLabel('Manual record notes', { exact: true }).fill('Unrevealed GM adjudication; no automatic escalation')
    await aftermath(gm).getByRole('button', { name: 'Save manual record', exact: true }).click()
    await expect(aftermath(gm).getByRole('article', { name: 'Manual consequence · PRIVATE_HANDOFF_MANDATE', exact: true })).toBeVisible()
    for (const page of [one, two]) {
      await expect(aftermath(page)).not.toContainText('PRIVATE_HANDOFF_MANDATE')
      await expect(page.getByLabel('Secret GM invitation')).toHaveCount(0)
    }
    await cycle(gm).getByLabel('Campaign phase', { exact: true }).selectOption('personal_business')
    await cycle(gm).getByRole('button', { name: 'Set phase', exact: true }).click()
    await two.reload()
    await expect(aftermath(two).getByText('Signal delivered; agreed crew balance is four stacks', { exact: true })).toBeVisible()
    await expect(cycle(two).getByText('Current phase: Personal Business', { exact: true })).toBeVisible()

    // Current ownership remains effective after the full cycle, including a reviewed transfer.
    for (const page of [gm, one, two]) await page.getByRole('tab', { name: 'Characters', exact: true }).click()
    for (const page of [gm, two]) await page.getByRole('button', { name: 'Open Moth', exact: true }).click()
    await expect(two.getByLabel('Alias', { exact: true })).toBeDisabled()
    await gm.getByRole('button', { name: 'Refresh participant list', exact: true }).click()
    await gm.getByLabel('Assign character to', { exact: true }).selectOption(await two.getByLabel('Your participant ID').inputValue())
    await gm.getByRole('button', { name: 'Review ownership change', exact: true }).click()
    await gm.getByRole('button', { name: 'Confirm ownership change', exact: true }).click()
    await expect(one.getByLabel('Alias', { exact: true })).toBeDisabled()
    await expect(two.getByLabel('Alias', { exact: true })).toBeEnabled()
    await two.getByLabel('Alias', { exact: true }).fill('New custodian')
    await two.getByLabel('Alias', { exact: true }).press('Tab')
    await expect(gm.getByLabel('Alias', { exact: true })).toHaveValue('New custodian')

    await gm.getByLabel('Character name', { exact: true }).scrollIntoViewIfNeeded()
    await gm.screenshot({ path: 'test-results/handoff-desktop.png' })
    await gm.getByRole('navigation', { name: 'Campaign sections', exact: true }).screenshot({ path: 'test-results/handoff-navigation.png' })
    await two.setViewportSize({ width: 390, height: 844 })
    const mobileSections = two.getByRole('navigation', { name: 'Campaign sections', exact: true })
    await mobileSections.getByRole('tab', { name: 'Cycle', exact: true }).focus()
    await two.keyboard.press('Enter')
    await two.keyboard.press('Tab')
    await expect(two.getByRole('tabpanel', { name: 'Cycle', exact: true })).toBeFocused()
    expect(await two.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await two.screenshot({ path: 'test-results/handoff-mobile-cycle.png' })
    await mobileSections.getByRole('tab', { name: 'Characters', exact: true }).focus()
    await two.keyboard.press('Enter')
    await two.keyboard.press('Tab')
    await expect(two.getByRole('tabpanel', { name: 'Characters', exact: true })).toBeFocused()
    await two.screenshot({ path: 'test-results/handoff-mobile-dossier.png' })
  } finally {
    await Promise.all(contexts.map(context => context.close()))
  }
})
