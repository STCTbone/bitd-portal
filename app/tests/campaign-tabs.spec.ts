import { test, expect } from '@playwright/test'

test('campaign tabs show one workspace, retain drafts and open overview dossiers', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Campaign name', { exact: true }).fill('Tabbed campaign')
  await page.getByRole('button', { name: 'Create campaign', exact: true }).click()
  const tabs = page.getByRole('tablist', { name: 'Campaign sections', exact: true })
  await expect(tabs.getByRole('tab', { name: 'Overview', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('[role="tabpanel"]:visible')).toHaveCount(1)
  await expect(page.getByLabel('Secret GM invitation')).not.toBeVisible()
  for (const name of ['Crew', 'Cycle', 'Factions', 'Map', 'Clocks', 'Media', 'Account', 'Setup', 'Characters', 'Notes']) {
    await tabs.getByRole('tab', { name, exact: true }).click()
    await expect(page.getByRole('tabpanel', { name, exact: true })).toBeVisible()
    await expect(page.locator('[role="tabpanel"]:visible')).toHaveCount(1)
  }
  await page.getByLabel('New note title', { exact: true }).fill('Keep this draft')
  await tabs.getByRole('tab', { name: 'Crew', exact: true }).click()
  await tabs.getByRole('tab', { name: 'Notes', exact: true }).click()
  await expect(page.getByLabel('New note title', { exact: true })).toHaveValue('Keep this draft')
  await tabs.getByRole('tab', { name: 'Characters', exact: true }).click()
  await page.getByLabel('New character name', { exact: true }).fill('Tab traveller')
  await page.getByRole('button', { name: 'Create Hound', exact: true }).click()
  await expect(page.getByLabel('Character name', { exact: true })).toHaveValue('Tab traveller')
  await tabs.getByRole('tab', { name: 'Overview', exact: true }).click()
  await page.getByRole('link', { name: 'Open Tab traveller dossier', exact: true }).click()
  await expect(page.getByRole('tabpanel', { name: 'Characters', exact: true })).toBeFocused()
  await expect(page.getByLabel('Character name', { exact: true })).toHaveValue('Tab traveller')
  await tabs.getByRole('tab', { name: 'Overview', exact: true }).click()
  await page.getByRole('link', { name: 'Open crew dossier', exact: true }).click()
  await expect(page.getByRole('tabpanel', { name: 'Crew', exact: true })).toBeVisible()
  await tabs.getByRole('tab', { name: 'Overview', exact: true }).click()
  await page.screenshot({ path: 'test-results/tabs-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await tabs.getByRole('tab', { name: 'Notes', exact: true }).click()
  await expect(page.getByLabel('New note title', { exact: true })).toHaveValue('Keep this draft')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/tabs-mobile.png' })
})

test('tabs support keyboard navigation, browser history, reload and legacy section addresses', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Campaign name', { exact: true }).fill('Keyboard campaign')
  await page.getByRole('button', { name: 'Create campaign', exact: true }).click()
  const tabs = page.getByRole('tablist', { name: 'Campaign sections', exact: true })
  const tab = (name: string) => tabs.getByRole('tab', { name, exact: true })
  await tab('Overview').focus()
  await page.keyboard.press('ArrowRight')
  await expect(tab('Characters')).toBeFocused()
  await expect(tab('Characters')).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('tabpanel', { name: 'Characters', exact: true })).toBeFocused()
  await tab('Characters').focus(); await page.keyboard.press('End')
  await expect(tab('Setup')).toBeFocused()
  await page.keyboard.press('ArrowRight'); await expect(tab('Overview')).toBeFocused()
  await page.keyboard.press('ArrowLeft'); await expect(tab('Setup')).toBeFocused()
  await page.keyboard.press('Home'); await expect(tab('Overview')).toBeFocused()
  await tab('Notes').click(); await tab('Crew').click()
  await page.goBack(); await expect(tab('Notes')).toHaveAttribute('aria-selected', 'true')
  await page.goForward(); await expect(tab('Crew')).toHaveAttribute('aria-selected', 'true')
  await page.reload(); await expect(tab('Crew')).toHaveAttribute('aria-selected', 'true')
  await page.goto('/#campaign-clocks'); await expect(tab('Clocks')).toHaveAttribute('aria-selected', 'true')
  await page.goto('/#unknown-section'); await expect(tab('Overview')).toHaveAttribute('aria-selected', 'true')
})

test('players have tabs for their campaign without the GM setup tab or invitation controls', async ({ page, browser }) => {
  await page.goto('/')
  await page.getByLabel('Campaign name', { exact: true }).fill('Player tabs')
  await page.getByRole('button', { name: 'Create campaign', exact: true }).click()
  await page.getByRole('tab', { name: 'Account', exact: true }).click()
  const invite = await page.getByLabel('Player invitation', { exact: true }).inputValue()
  const context = await browser.newContext()
  try {
    const player = await context.newPage(); await player.goto('/')
    await player.getByLabel('Invitation', { exact: true }).fill(invite)
    await player.getByRole('button', { name: 'Join campaign', exact: true }).click()
    await expect(player.getByRole('tab', { name: 'Setup', exact: true })).toHaveCount(0)
    await player.getByRole('tab', { name: 'Account', exact: true }).click()
    await expect(player.getByLabel('Secret GM invitation')).toHaveCount(0)
    await player.goto('/#campaign-setup')
    await expect(player.getByRole('tab', { name: 'Overview', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(player.locator('[role="tabpanel"]:visible')).toHaveCount(1)
  } finally { await context.close() }
})
