import { test, expect } from '@playwright/test'
import { createClient } from '@supabase/supabase-js'
const url = process.env.VITE_SUPABASE_URL!, key = process.env.VITE_SUPABASE_ANON_KEY!
if (!url || !['127.0.0.1', 'localhost'].includes(new URL(url).hostname)) throw new Error('Tests require local Supabase')
const client = () => createClient(url, key, { db: { schema: 'bitd' }, auth: { persistSession: false, autoRefreshToken: false } })

test('condition records use published capacities and preserve deliberate owner/GM changes without automatic consequences', async () => {
  const gm = client(), player = client(), other = client(), outsider = client()
  for (const c of [gm, player, other, outsider]) expect((await c.auth.signInAnonymously()).error).toBeNull()
  const campaign = (await gm.rpc('create_campaign', { p_name: 'Condition records' })).data.id
  const invitation = (await gm.rpc('get_campaign_invitations', { p_campaign: campaign })).data.player
  for (const c of [player, other]) await c.rpc('join_campaign', { p_invitation: invitation })
  const made = await player.rpc('create_character', { p_campaign: campaign, p_name: 'Reed' })
  expect(made.error).toBeNull()
  const id = made.data.id
  expect(made.data.data).toMatchObject({ stress: 0, stressCapacity: 9, keyCapacity: 4, keys: [], deadlocks: [], healing: { progress: 0, permanent: 0 }, harm: { passing: ['', ''], major: ['', ''], critical: [''], mortal: [''] } })
  const keys = [{ name: 'Curious', hits: 3 }]
  const deadlocks = [{ name: 'Cold', formerKey: 'Charming', notes: 'Crisis at the docks' }]
  expect((await player.rpc('patch_character', { p_character: id, p_patch: { stress: 9, keys, deadlocks, harm: { mortal: ['Lethal wound'] }, healing: { progress: 4 }, recoveryNotes: 'Waiting for GM intervention' } })).error).toBeNull()
  const saved = (await player.from('characters').select('*').eq('id', id).single()).data!.data
  expect(saved).toMatchObject({ stress: 9, keys, deadlocks, healing: { progress: 4, permanent: 0 }, harm: { passing: ['', ''], mortal: ['Lethal wound'] } })
  expect(saved.actions.consort).toBe(2)
  for (const c of [other, outsider]) expect((await c.rpc('patch_character', { p_character: id, p_patch: { stress: 0 } })).error).not.toBeNull()
  for (const patch of [{ keys: Array.from({ length: 5 }, () => ({ name: 'Fifth Key', hits: 0 })), deadlocks: [] }, { stress: 10 }, { stress: -1 }, { stress: 1.5 }, { stressCapacity: 100 }, { keyCapacity: 20 }, { keys: [{ name: 'Too marked', hits: 4 }] }, { deadlocks: [{ name: 'Fake', role: 'gm' }] }, { harm: { major: ['One', 'Two', 'Three'] } }, { harm: { hidden: 'secret' } }, { healing: { progress: 5 } }, { healing: { admin: true } }, { owner_id: 'forged' }, { playbook: 'Hull' }]) expect((await player.rpc('patch_character', { p_character: id, p_patch: patch })).error, JSON.stringify(patch)).not.toBeNull()
  for (const patch of [
    { healing: { progress: 0, permanent: 1 }, versatile: [{ name: 'Get Back In There', source: 'Veteran', notes: '' }] },
    { abilities: ['Versatile'], healing: { progress: 0, permanent: 1 }, versatile: [{ name: 'Get Back In There', source: '', notes: '' }] },
  ]) expect((await player.rpc('patch_character', { p_character: id, p_patch: patch })).error).not.toBeNull()
  expect((await player.rpc('set_character_key_capacity', { p_character: id, p_capacity: 5, p_reason: 'Crew upgrade' })).error).not.toBeNull()
  expect((await outsider.rpc('set_character_key_capacity', { p_character: id, p_capacity: 5, p_reason: 'Crew upgrade' })).error).not.toBeNull()
  expect((await gm.rpc('set_character_key_capacity', { p_character: id, p_capacity: 5, p_reason: 'Verified crew upgrade: one additional Key/Deadlock' })).error).toBeNull()
  expect((await player.rpc('patch_character', { p_character: id, p_patch: { keys: [], deadlocks: Array.from({ length: 5 }, (_, i) => ({ name: `Deadlock ${i}`, formerKey: '', notes: '' })) } })).error).toBeNull()
  expect((await gm.rpc('set_character_key_capacity', { p_character: id, p_capacity: 4, p_reason: 'Undo upgrade' })).error).not.toBeNull()
  const edits = await Promise.all([
    player.rpc('patch_character', { p_character: id, p_patch: { harm: { passing: ['Bruised', ''] }, healing: { progress: 1 } } }),
    gm.rpc('patch_character', { p_character: id, p_patch: { harm: { critical: ['Broken leg'] }, recoveryNotes: 'Reviewed treatment; no automatic healing' } }),
  ])
  for (const edit of edits) expect(edit.error).toBeNull()
  expect((await player.from('characters').select('data').eq('id', id).single()).data!.data).toMatchObject({ stress: 9, keyCapacity: 5, harm: { passing: ['Bruised', ''], critical: ['Broken leg'], mortal: ['Lethal wound'] }, healing: { progress: 1, permanent: 0 } })
  expect((await player.from('characters').update({ data: { stress: 0 } }).eq('id', id)).error).not.toBeNull()
})

test('players review condition edits, share accepted state, correct injuries and retry rejected saves', async ({ browser }) => {
  test.setTimeout(60000)
  const contexts = await Promise.all([browser.newContext(), browser.newContext(), browser.newContext()])
  const [gm, player, observer] = await Promise.all(contexts.map(c => c.newPage()))
  await gm.goto('/')
  await gm.getByLabel('Campaign name').fill('Midnight recovery')
  await gm.getByRole('button', { name: 'Create campaign', exact: true }).click()
  const invitation = await gm.getByLabel('Player invitation').inputValue()
  for (const page of [player, observer]) {
    await page.goto('/')
    await page.getByLabel('Invitation', { exact: true }).fill(invitation)
    await page.getByRole('button', { name: 'Join campaign', exact: true }).click()
  }
  await player.getByLabel('New character name').fill('Reed')
  await player.getByRole('button', { name: 'Create Hound', exact: true }).click()
  for (const page of [gm, observer]) await page.getByRole('button', { name: 'Open Reed', exact: true }).click()
  await expect(player.getByLabel('Stress marked', { exact: true })).toHaveValue('0')
  await expect(observer.getByLabel('Stress marked', { exact: true })).toBeDisabled()
  await player.getByLabel('Stress marked', { exact: true }).selectOption('9')
  await player.getByRole('button', { name: 'Add Key', exact: true }).click()
  await player.getByLabel('Key 1 name', { exact: true }).fill('Curious')
  await player.getByLabel('Key 1 hits', { exact: true }).selectOption('3')
  await player.getByLabel('Mortal Harm 1', { exact: true }).fill('Shattered heart')
  await player.getByLabel('Healing progress', { exact: true }).selectOption('4')
  await player.getByLabel('Recovery notes', { exact: true }).fill('Miraculous treatment discussed with GM')
  await expect(observer.getByLabel('Stress marked', { exact: true })).toHaveValue('0')
  await player.getByRole('button', { name: 'Review condition changes', exact: true }).click()
  await expect(player.getByRole('region', { name: 'Review condition changes', exact: true })).toContainText('Shattered heart')
  await expect(observer.getByLabel('Mortal Harm 1', { exact: true })).toHaveValue('')
  await player.getByRole('button', { name: 'Confirm condition changes', exact: true }).click()
  await expect(observer.getByLabel('Stress marked', { exact: true })).toHaveValue('9')
  await expect(observer.getByLabel('Key 1 hits', { exact: true })).toHaveValue('3')
  await expect(observer.getByLabel('Mortal Harm 1', { exact: true })).toHaveValue('Shattered heart')
  await expect(observer.getByLabel('Healing progress', { exact: true })).toHaveValue('4')
  await expect(observer.getByLabel(/Deadlock 1 name/)).toHaveCount(0)
  await expect(observer.getByLabel('Consort rating')).toHaveValue('2')
  // Recording terminal tracks does not retire, erase harm, clear Stress or award XP.
  await player.getByRole('button', { name: 'Remove Key 1', exact: true }).click()
  await player.getByRole('button', { name: 'Add Deadlock', exact: true }).click()
  await player.getByLabel('Deadlock 1 name', { exact: true }).fill('Obsessive')
  await player.getByLabel('Deadlock 1 former Key', { exact: true }).fill('Curious')
  await player.getByLabel('Stress marked', { exact: true }).selectOption('0')
  await player.getByLabel('Mortal Harm 1', { exact: true }).fill('')
  await player.getByLabel('Critical Harm 1', { exact: true }).fill('Scarred chest')
  await player.getByLabel('Healing progress', { exact: true }).selectOption('1')
  await player.getByRole('button', { name: 'Review condition changes', exact: true }).click()
  await contexts[1].setOffline(true)
  await player.getByRole('button', { name: 'Confirm condition changes', exact: true }).click()
  await expect(player.getByRole('alert').filter({ hasText: 'Condition changes were not saved' })).toBeVisible()
  await expect(observer.getByLabel('Stress marked', { exact: true })).toHaveValue('9')
  await contexts[1].setOffline(false)
  await player.getByRole('button', { name: 'Retry condition changes', exact: true }).click()
  await expect(observer.getByLabel('Deadlock 1 name', { exact: true })).toHaveValue('Obsessive')
  await expect(observer.getByLabel('Critical Harm 1', { exact: true })).toHaveValue('Scarred chest')
  await expect(observer.getByLabel('Stress marked', { exact: true })).toHaveValue('0')
  await player.reload()
  await player.getByRole('button', { name: 'Open Reed', exact: true }).click()
  await expect(player.getByLabel('Healing progress', { exact: true })).toHaveValue('1')
  // A published ability exception remains distinct from ordinary healing marks.
  await player.getByLabel('Permanent healing segments', { exact: true }).selectOption('1')
  await player.getByRole('button', { name: 'Review condition changes', exact: true }).click()
  await player.getByRole('button', { name: 'Confirm condition changes', exact: true }).click()
  await expect(player.getByRole('alert').filter({ hasText: 'Condition changes were not saved' })).toContainText('Get Back In There')
  await player.getByRole('button', { name: 'Discard condition changes', exact: true }).click()
  await expect(player.getByLabel('Permanent healing segments', { exact: true })).toHaveValue('0')
  await player.getByLabel('Versatile', { exact: true }).click()
  await expect(player.getByLabel('Versatile', { exact: true })).toBeChecked()
  await player.getByRole('button', { name: 'Add Versatile ability', exact: true }).click()
  await player.getByLabel('Versatile 1 name', { exact: true }).fill('Get Back In There')
  await player.getByLabel('Versatile 1 name', { exact: true }).blur()
  await expect(observer.getByLabel('Versatile 1 name', { exact: true })).toHaveValue('Get Back In There')
  await player.getByLabel('Versatile 1 source', { exact: true }).fill('Veteran · book v1.0.1 p.84')
  await player.getByLabel('Versatile 1 source', { exact: true }).blur()
  await expect(observer.getByLabel('Versatile 1 source', { exact: true })).toHaveValue('Veteran · book v1.0.1 p.84')
  await player.getByLabel('Permanent healing segments', { exact: true }).selectOption('1')
  await player.getByLabel('Healing progress', { exact: true }).selectOption('3')
  await player.getByRole('button', { name: 'Review condition changes', exact: true }).click()
  await player.getByRole('button', { name: 'Confirm condition changes', exact: true }).click()
  await expect(observer.getByLabel('Permanent healing segments', { exact: true })).toHaveValue('1')
  await expect(observer.getByLabel('Healing progress', { exact: true })).toHaveValue('3')
  await expect(observer.getByLabel('Critical Harm 1', { exact: true })).toHaveValue('Scarred chest')
  await player.getByRole('region', { name: 'Condition records', exact: true }).screenshot({ path: 'test-results/conditions-desktop.png' })
  await gm.getByLabel('Key capacity source', { exact: true }).fill('Crew upgrade: extra Key')
  await gm.getByLabel('Key/Deadlock capacity', { exact: true }).selectOption('5')
  await gm.getByRole('button', { name: 'Confirm Key capacity', exact: true }).click()
  await expect(observer.getByText('1 / 5 Key and Deadlock slots occupied', { exact: true })).toBeVisible()
  await player.setViewportSize({ width: 390, height: 844 })
  expect(await player.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await player.getByRole('region', { name: 'Condition records', exact: true }).screenshot({ path: 'test-results/conditions-mobile.png' })
  for (const context of contexts) await context.close()
})
